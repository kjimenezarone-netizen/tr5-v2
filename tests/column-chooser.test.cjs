const assert = require('node:assert/strict');
const chooser = require('../column-chooser.js');
const parser = require('../file-parser.js');
const tr = require('../tr-analysis.js');
const a = {}, b = {};
const columns = ['Documento', 'Nombres', 'Fecha'];
chooser.toggle(a, columns, 'Nombres', false);
assert.deepEqual(chooser.visible(a, columns), ['Documento', 'Fecha']);
assert.deepEqual(chooser.visible(b, columns), columns, 'Configuración independiente por fuente');
chooser.toggle(a, columns, 'Fecha', false);
chooser.toggle(a, columns, 'Documento', false);
assert.deepEqual(chooser.visible(a, columns), ['Documento'], 'Al menos una columna visible');
chooser.toggle(a, columns, 'No existe', false);
assert.deepEqual(chooser.visible(a, columns), ['Documento']);
chooser.toggle(a, columns, 'Nombres', true);
assert.deepEqual(chooser.visible(a, columns), ['Documento', 'Nombres']);
assert.deepEqual(chooser.visible(a, [...columns,'Nueva']), ['Documento','Nombres','Nueva']);
chooser.reset(a);assert.deepEqual(chooser.visible(a,columns),columns);
