const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(__dirname+'/Code.gs','utf8')+'\nglobalThis.api={registrar_,login_,sesion_};',context);
const input={eventId:'12345678-1234-1234-1234-123456789012',intendencia:'IRE-LIMA',modulo:'RUC',accion:'VISUALIZACIÓN',registros:100,archivos:1,duracionMs:100,bytes:44464,version:'2.0'};
assert.equal(context.api.registrar_({...input,nombres:'no permitido'}).status,'invalid_event');
assert.equal(context.api.registrar_({...input,registros:-1}).status,'invalid_event');
assert.equal(context.api.registrar_({...input,intendencia:'=FORMULA()'}).status,'invalid_event');
assert.equal(context.api.registrar_({...input,version:'=FORMULA()'}).status,'invalid_event');
assert.equal(context.api.registrar_({...input,modulo:'OTRO'}).status,'invalid_event');
let written, released=false;
context.LockService={getScriptLock:()=>({waitLock(){},releaseLock(){released=true}})};
context.hoja_=()=>({getLastRow:()=>1,appendRow:row=>{written=row}});
assert.equal(context.api.registrar_(input).status,'ok');
assert.equal(written.length,10);assert.equal(written[5],100);assert.ok(released);
written=null;
context.hoja_=()=>({getLastRow:()=>2,getRange:()=>({createTextFinder:()=>({matchEntireCell:()=>({findNext:()=>true})})}),appendRow:row=>{written=row}});
assert.equal(context.api.registrar_(input).duplicate,true);assert.equal(written,null);
context.PropertiesService={getScriptProperties:()=>({getProperty:()=>null})};
assert.equal(context.api.login_({}).status,'not_configured');
console.log('OK: validación de eventos, campos privados, fórmulas, escritura, duplicados y login sin configuración.');
